"""Builds the private Python that ships inside the PMO Desk installer.

The Tasks engine and every task script run on this interpreter: the official
Windows *embeddable* CPython plus the pinned packages from
tasks-engine/requirements.txt and tasks/requirements.txt (pytest and other test
tools are left out). Nothing is compiled: every package is a published binary
wheel, installed with `--require-hashes` from scripts/python-runtime/requirements.lock.txt.

    python scripts/build-python-runtime.py build [--out build/python-runtime]
    python scripts/build-python-runtime.py lock      # re-resolve and re-pin (needs network)

`build` needs any Python 3.9+ with pip on the machine that builds the installer
(it only drives pip with --platform win_amd64; the runtime it produces does not
depend on it) and network access the first time (downloads are cached in
build/.cache). It is idempotent: when the pins have not changed it does nothing.
Output: <out>/python/ (python.exe, pythonw.exe, Lib/site-packages), which
electron-builder copies to resources/python.

Pins live in scripts/python-runtime/runtime.json (interpreter: URL + SHA-256 of
the python.org embeddable zip) and requirements.lock.txt (every package, with
hashes). To upgrade: edit the versions in the two requirements.txt files (or the
interpreter pin), run `lock`, review the diff, then `build`.
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PIN_DIR = ROOT / "scripts" / "python-runtime"
RUNTIME_PIN = PIN_DIR / "runtime.json"
LOCK_FILE = PIN_DIR / "requirements.lock.txt"
SOURCE_REQUIREMENTS = [ROOT / "tasks-engine" / "requirements.txt", ROOT / "tasks" / "requirements.txt"]
# Test and developer tools: pinned for the dev venv, never shipped.
NOT_SHIPPED = {"pytest", "pytest-cov", "coverage", "httpx"}
DEFAULT_OUT = ROOT / "build" / "python-runtime"
CACHE = ROOT / "build" / ".cache"
STAMP = ".runtime-stamp"
# Bump when this script changes what it produces (the pins alone drive the rest).
RECIPE_REVISION = "2"
# Packages that are pure test fixtures inside the wheels (large in numpy/scipy).
PRUNE_DIR_NAMES = {"tests", "__pycache__"}
IMPORT_CHECK = (
    "import fastapi, uvicorn, multipart, openpyxl, xlsxwriter, numpy, scipy.optimize, lxml.etree, PIL;"
    "import sys; print(sys.version.split()[0])"
)


def pin() -> dict:
    return json.loads(RUNTIME_PIN.read_text(encoding="utf-8"))


def direct_requirements() -> list[str]:
    lines = []
    for path in SOURCE_REQUIREMENTS:
        for raw in path.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line or line.startswith("-"):
                continue
            name = re.split(r"[=<>!~\[ ]", line, maxsplit=1)[0].lower().replace("_", "-")
            if name not in NOT_SHIPPED:
                lines.append(line)
    return lines


def platform_args(p: dict) -> list[str]:
    major, minor = p["python"].split(".")[:2]
    return [
        "--only-binary=:all:", "--platform", "win_amd64",
        "--python-version", f"{major}.{minor}", "--implementation", "cp", "--abi", f"cp{major}{minor}",
    ]


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def pip(*args: str) -> None:
    subprocess.run([sys.executable, "-m", "pip", "--disable-pip-version-check", *args], check=True)


def lock() -> None:
    """Resolve the direct requirements for win_amd64/cp313 and pin every wheel with its hash."""
    p = pin()
    with tempfile.TemporaryDirectory(prefix="ai-os-lock-") as tmp:
        wheels = Path(tmp) / "wheels"
        req = Path(tmp) / "direct.txt"
        req.write_text("\n".join(direct_requirements()) + "\n", encoding="utf-8")
        pip("download", "-q", "-d", str(wheels), "-r", str(req), *platform_args(p))
        entries = {}
        for wheel in sorted(wheels.glob("*.whl")):
            name, version = wheel.name.split("-")[:2]
            entries[name.lower().replace("_", "-")] = (version, sha256_of(wheel))
    body = ["# Generated by scripts/build-python-runtime.py lock - do not edit by hand.",
            f"# win_amd64, CPython {p['python'].rsplit('.', 1)[0]}; every wheel pinned with its SHA-256."]
    for name in sorted(entries):
        version, digest = entries[name]
        body.append(f"{name}=={version} --hash=sha256:{digest}")
    LOCK_FILE.write_text("\n".join(body) + "\n", encoding="utf-8", newline="\n")
    print(f"pinned {len(entries)} packages -> {LOCK_FILE}")


def fingerprint() -> str:
    parts = [RECIPE_REVISION, RUNTIME_PIN.read_text(encoding="utf-8"), LOCK_FILE.read_text(encoding="utf-8")]
    return hashlib.sha256("\n".join(parts).encode("utf-8")).hexdigest()


def download(p: dict) -> Path:
    CACHE.mkdir(parents=True, exist_ok=True)
    target = CACHE / p["file"]
    if not target.exists() or sha256_of(target) != p["sha256"]:
        print(f"downloading {p['url']}")
        tmp = target.with_suffix(".part")
        with urllib.request.urlopen(p["url"], timeout=120) as response, tmp.open("wb") as out:
            shutil.copyfileobj(response, out)
        if sha256_of(tmp) != p["sha256"]:
            tmp.unlink()
            raise SystemExit(f"SHA-256 mismatch for {p['url']}: refusing to use it")
        tmp.replace(target)
    return target


def drop_path_file(python_dir: Path, p: dict) -> None:
    """Remove the embeddable's `python313._pth`.

    That file puts the interpreter in isolated mode: no PYTHONPATH and, what
    matters here, no script folder on sys.path, which the task scripts rely on
    (`from _common import ...`). Without it the stdlib zip, the interpreter folder
    and Lib/site-packages are found next to python.exe as usual. The engine starts
    it with PYTHONNOUSERSITE=1 so nothing from a user-level Python leaks in, and with
    PYTHONHOME set to this folder (embeddedPythonHome in src/lib/tasks-engine) so the
    registry entries of a python.org Python on the machine are not read either."""
    major, minor = p["python"].split(".")[:2]
    (python_dir / f"python{major}{minor}._pth").unlink(missing_ok=True)


def prune(site_packages: Path) -> None:
    for path in sorted(site_packages.rglob("*"), key=lambda q: len(q.parts), reverse=True):
        if path.is_dir() and path.name in PRUNE_DIR_NAMES and path != site_packages:
            shutil.rmtree(path, ignore_errors=True)


def build(out: Path) -> None:
    p = pin()
    python_dir = out / "python"
    stamp = python_dir / STAMP
    wanted = fingerprint()
    if stamp.is_file() and stamp.read_text(encoding="utf-8").strip() == wanted and (python_dir / "python.exe").is_file():
        print(f"python runtime is up to date: {python_dir}")
        return

    archive = download(p)
    if python_dir.exists():
        shutil.rmtree(python_dir)
    python_dir.mkdir(parents=True)
    with zipfile.ZipFile(archive) as zf:
        zf.extractall(python_dir)
    drop_path_file(python_dir, p)

    site_packages = python_dir / "Lib" / "site-packages"
    site_packages.mkdir(parents=True)
    pip("install", "-q", "--no-deps", "--require-hashes", "--target", str(site_packages),
        "-r", str(LOCK_FILE), *platform_args(p))
    prune(site_packages)

    exe = python_dir / "python.exe"
    # -I: the check runs without any user site or environment influence.
    subprocess.run([str(exe), "-I", "-m", "compileall", "-q", "-j", "0", str(site_packages)], check=True)
    done = subprocess.run([str(exe), "-I", "-c", IMPORT_CHECK], capture_output=True, text=True, check=False)
    if done.returncode != 0:
        raise SystemExit(f"the built runtime failed its import check:\n{done.stderr[-1500:]}")
    stamp.write_text(wanted + "\n", encoding="utf-8")
    size = sum(f.stat().st_size for f in python_dir.rglob("*") if f.is_file())
    print(f"built Python {done.stdout.strip()} runtime: {python_dir} ({size / 1048576:.0f} MB)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    build_cmd = sub.add_parser("build", help="build (or reuse) the runtime")
    build_cmd.add_argument("--out", type=Path, default=DEFAULT_OUT)
    sub.add_parser("lock", help="re-resolve and re-pin the packages")
    args = parser.parse_args()
    if args.command == "lock":
        lock()
    else:
        build(args.out.resolve())


if __name__ == "__main__":
    main()
