def shift_group_rule(
    schedule: Mapping[str, Mapping[date, str]],
    team_of: Callable[[str], str],
    minimum_for: Callable[[str], int | None],
    per_team_day: Callable[[str], bool] | None = None,
    works_hint: Mapping[str, Callable[[date], bool | None]] | None = None,
) -> Callable[[str, date], tuple[Hashable, int] | None]:
    """Build a `min_staff_for` for `apply_pto`: group = (team, canonical shift on that day).

    `team_of(name)` and `minimum_for(name)` come from the caller (roster/config);
    people not on a shift that day have no rule. `per_team_day(name)` -> True marks people
    of a per_team_day team: their group is the whole team that day, (team, "ALL"), counting
    every working cell, with the EFFECTIVE minimum min(minimum, members of the team
    scheduled that day before leave/HOL) (see `checks.effective_min`).
    """
    cells = ({n: PersonCells(c, (works_hint or {}).get(n)) for n, c in schedule.items()}
             if per_team_day else {})
    scheduled: dict[tuple[str, date], int] = {}

    def team_scheduled(team: str, d: date) -> int:
        if (team, d) not in scheduled:
            scheduled[(team, d)] = sum(1 for n, pc in cells.items()
                                       if team_of(n) == team and scheduled_on(pc, d))
        return scheduled[(team, d)]

    def rule(name: str, d: date):
        parsed = try_parse_code(schedule.get(name, {}).get(d, ""))
        if per_team_day is not None and per_team_day(name):
            if parsed is None or not is_working_code(parsed.canonical):
                return None
            minimum = minimum_for(name)
            if minimum is None:
                return None
            team = team_of(name)
            return (team, ALL_SHIFTS), min(minimum, team_scheduled(team, d))
        if parsed is None or DEFAULT_TABLE[parsed.canonical].kind is not Kind.SHIFT:
            return None
        minimum = minimum_for(name)
        return None if minimum is None else ((team_of(name), parsed.canonical), minimum)
    return rule


def _would_work(text: str) -> bool:
    parsed = try_parse_code(text)
    return parsed is not None and (is_working_code(parsed.canonical) or parsed.canonical == HOL)


def apply_pto(
    schedule: Mapping[str, Mapping[date, str]],
    entries: Iterable[PtoEntry],
    cycle: Cycle,
    confirmed: Mapping[str, str] | None = None,
    *,
    needed: Iterable[tuple[str, date]] | None = None,
    min_staff_for: Callable[[str, date], tuple[Hashable, int] | None] | None = None,
    preserved: Iterable[tuple[str, date]] = (),
) -> PtoResult:
    """Turn PTO entries into schedule edits for `cycle`; see the module docstring."""
    entries = list(entries)
    match = match_names((e.name for e in entries), schedule.keys(), confirmed)
    needed_set = set(needed or ())
    kept = set(preserved)
    edits: dict[tuple[str, date], str] = {}
    clashes: list[PtoClash] = []
    notes: list[str] = []
    skipped: list[PtoEntry] = []
    skipped_leave: dict[tuple[str, date], str] = {}

    for entry in entries:
        person = match.exact.get(entry.name)
        if person is None:
            skipped.append(entry)
            continue
        first, last = max(entry.start, cycle.start), min(entry.end, cycle.end)
        if first > last:
            notes.append(f"row {entry.row}: {entry.name} {entry.start:%d-%b-%Y}..{entry.end:%d-%b-%Y} "
                         f"is outside {cycle.label} and was ignored")
            continue
        d = first
        while d <= last:
            text = schedule[person].get(d, "")
            key = (person, d)
            if key in kept:
                # a leave code typed by hand and preserved (a HOL too): it stays, PTO does not
                # replace it (HOL would otherwise lose to PTO); a note says so
                existing = try_parse_code(text)
                if existing is not None and existing.canonical != entry.code:
                    skipped_leave[key] = existing.canonical
            elif _would_work(text):
                if key in edits and edits[key] != entry.code:
                    clashes.append(PtoClash(person, d, "OVERLAP",
                                            f"row {entry.row} ({entry.code}) conflicts with an "
                                            f"earlier entry ({edits[key]}); the earlier one is kept"))
                elif key not in edits:
                    edits[key] = entry.code
            elif (parsed := try_parse_code(text)) and is_leave_code(parsed.canonical) \
                    and parsed.canonical != entry.code:
                skipped_leave[(person, d)] = parsed.canonical
            d += timedelta(days=1)

    for (person, d), code in sorted(skipped_leave.items()):
        notes.append(f"{person} {d:%d-%b-%Y}: already {code}; PTO not written")
    if skipped:
        notes.append(f"{len(skipped)} PTO entr{'y' if len(skipped) == 1 else 'ies'} skipped until "
                     "the name is confirmed or fixed (see the match report)")

    for (person, d) in sorted(edits, key=lambda k: (k[1], k[0])):
        if d == cycle.rotation_sunday:
            clashes.append(PtoClash(person, d, "SWAP_SUNDAY", "PTO on the swap Sunday"))
        if (person, d) in needed_set:
            clashes.append(PtoClash(person, d, "NEEDED", "PTO on a day the person is needed for "
                                                         "coverage"))
    if min_staff_for is not None:
        clashes.extend(_below_min(schedule, edits, min_staff_for))
    return PtoResult(edits, clashes, notes, match, skipped)


def _below_min(schedule, edits, min_staff_for) -> list[PtoClash]:
    out: list[PtoClash] = []
    for d in sorted({d for _, d in edits}):
        minimum_of: dict[Hashable, int] = {}
        working: dict[Hashable, int] = {}
        pto_people: dict[Hashable, list[str]] = {}
        for name in schedule:
            rule = min_staff_for(name, d)
            if rule is None:
                continue
            group, minimum = rule
            minimum_of[group] = minimum
            working.setdefault(group, 0)
            if (name, d) in edits:
                pto_people.setdefault(group, []).append(name)
            else:
                parsed = try_parse_code(schedule[name].get(d, ""))
                if parsed is not None and is_working_code(parsed.canonical):
                    working[group] += 1
        for group, people in pto_people.items():
            if working[group] < minimum_of[group]:
                for name in sorted(people):
                    out.append(PtoClash(name, d, "BELOW_MIN",
                                        f"{working[group]} left on {group}, minimum "
                                        f"{minimum_of[group]}"))
    return out
