"""
Step 3 "PTO import": read the PTO workbook, match names, write leave codes.

Workbook (see `examples/pto_import_template.xlsx`, `pto_template.py`): columns
Name | From | To | Code. Headers are found by content on the first rows
(case/spacing/punctuation tolerant: "Name", "from", "Start Date", "To",
"End", "Code", "Type"...); the sheet is "PTO" if present, else the first sheet
that is not "Notes". Code defaults to `P`; only P, T and SL may be imported
(HOL is generated by the holiday engine, COMP is never generated, and shift
codes are not leave). Dates are date cells or text (ISO, `21-Dec-2026`,
day-first `21/12/2026`). `To` is inclusive. All bad rows are reported at once in
`PtoImportError` with their sheet row numbers.

Name matching (`match_names`), adapted from `shared/roster/name_matching.py`:
  exact         same words ignoring case, order and dots -> silent;
  fuzzy         one word more/less, or one word within edit distance 2, or the
                whole name within edit distance 2 -> `needs_confirmation` with
                candidates; NEVER accepted silently (the PMO is asked);
  none          -> `unmatched`.
`confirmed` ({import name: roster name}) holds answers to earlier questions;
a confirmed pair counts as exact. A name that equally matches two roster people
is ambiguous and needs confirmation. Entries whose name is not exact/confirmed
are skipped by `apply_pto` and listed in `PtoResult.match`.

`apply_pto(schedule, entries, cycle, confirmed, ...)` -> `PtoResult`:
  - writes the code on a date inside the cycle and [From, To] ONLY if the
    person would otherwise work that day (current text is a working code) or
    holds HOL (PTO wins over HOL); weekly offs (blank) and other leave stay;
  - never looks for replacements;
  - ranges outside the cycle are ignored with a note; the part inside is used;
  - clashes (reported, still applied): PTO on the swap Sunday, on a day the
    person is in `needed`, or dropping a team's shift below its minimum
    (`min_staff_for(name, date) -> (group, minimum) | None`, group is any
    hashable such as (team, shift) or, for a per_team_day team, (team, "ALL") with
    the effective minimum; see `shift_group_rule`); overlapping
    entries with different codes keep the first;
  - `preserved` ((name, date) cells holding a leave code that must stay, e.g. typed by hand
    in the master): a PTO entry on one keeps the existing code (HOL included) and adds
    the note "already X; PTO not written".
Edits are `{(name, date): text}`; the schedule is not modified.
"""

from __future__ import annotations

import datetime as dt
import re
from dataclasses import dataclass, field
from datetime import date, timedelta
from pathlib import Path
from typing import Callable, Hashable, Iterable, Mapping

import openpyxl

from .checks import ALL_SHIFTS, PersonCells, scheduled_on
from .codes import DEFAULT_TABLE, HOL, P, SL, T, Kind, is_leave_code, is_working_code, try_parse_code
from .config import name_key
from .cycles import Cycle

ALLOWED_PTO_CODES = frozenset({P, T, SL})
DEFAULT_PTO_CODE = P
_HEADER_SCAN_ROWS = 25
_HEADER_ALIASES = {
    "name": {"name", "fullname", "employee", "employeename", "person", "resource"},
    "from": {"from", "start", "startdate", "fromdate", "begin"},
    "to": {"to", "end", "enddate", "todate", "until"},
    "code": {"code", "type", "leavecode", "leavetype", "leave"},
}
_DATE_FORMATS = ("%Y-%m-%d", "%d-%b-%Y", "%d %b %Y", "%d-%B-%Y", "%d %B %Y", "%d/%m/%Y",
                 "%d-%m-%Y", "%d.%m.%Y", "%d/%b/%Y", "%Y/%m/%d")


class PtoImportError(ValueError):
    """The PTO workbook has bad rows; `problems` lists every one with its row number."""

    def __init__(self, problems: list[str]):
        super().__init__("PTO import problems:\n- " + "\n- ".join(problems))
        self.problems = list(problems)


@dataclass(frozen=True)
class PtoEntry:
    name: str  # as typed in the import file
    start: date
    end: date  # inclusive
    code: str  # P, T or SL
    row: int  # sheet row (for messages)


@dataclass(frozen=True)
class Candidate:
    roster_name: str
    reason: str


@dataclass
class PtoMatchReport:
    exact: dict[str, str] = field(default_factory=dict)  # import name -> roster name
    needs_confirmation: dict[str, list[Candidate]] = field(default_factory=dict)
    unmatched: list[str] = field(default_factory=list)
    via_confirmation: frozenset[str] = frozenset()  # exact entries that came from `confirmed`

    @property
    def complete(self) -> bool:
        return not self.needs_confirmation and not self.unmatched


@dataclass(frozen=True)
class PtoClash:
    person: str
    date: date
    kind: str  # SWAP_SUNDAY | NEEDED | BELOW_MIN | OVERLAP
    detail: str


@dataclass
class PtoResult:
    edits: dict[tuple[str, date], str]
    clashes: list[PtoClash]
    notes: list[str]
    match: PtoMatchReport
    skipped_entries: list[PtoEntry]  # not applied because the name is not confirmed/matched


# ---- reading the workbook -------------------------------------------------------

def _norm_header(value: object) -> str:
    return re.sub(r"[^a-z0-9]", "", str(value).casefold()) if value is not None else ""


def _to_date(value: object) -> date | None:
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, date):
        return value
    if isinstance(value, (int, float)) and not isinstance(value, bool) and 20000 < value < 80000:
        return (dt.datetime(1899, 12, 30) + timedelta(days=float(value))).date()
    if isinstance(value, str):
        text = " ".join(value.split())
        for fmt in _DATE_FORMATS:
            try:
                return dt.datetime.strptime(text, fmt).date()
            except ValueError:
                continue
    return None


def _pick_sheet(wb):
    for ws in wb.worksheets:
        if ws.title.strip().casefold() == "pto":
            return ws
    for ws in wb.worksheets:
        if ws.title.strip().casefold() != "notes":
            return ws
    raise PtoImportError(["the workbook has no PTO sheet"])


def read_pto_workbook(path: str | Path) -> list[PtoEntry]:
    """Read and validate the PTO import file; raises `PtoImportError` listing every bad row."""
    try:
        wb = openpyxl.load_workbook(path, data_only=True, read_only=True)
    except Exception as exc:  # unreadable/corrupt file
        raise PtoImportError([f"cannot open {Path(path).name}: {exc}"]) from exc
    try:
        rows = [list(r) for r in _pick_sheet(wb).iter_rows(values_only=True)]
    finally:
        wb.close()
    return parse_pto_rows(rows)


def parse_pto_rows(rows: list[list]) -> list[PtoEntry]:
    """Same as `read_pto_workbook` for rows already read (row 1 = first item)."""
    header_row, columns = None, {}
    for i, row in enumerate(rows[:_HEADER_SCAN_ROWS]):
        found = {}
        for j, value in enumerate(row):
            key = _norm_header(value)
            for field_name, aliases in _HEADER_ALIASES.items():
                if key in aliases and field_name not in found:
                    found[field_name] = j
        if {"name", "from", "to"} <= set(found):
            header_row, columns = i, found
            break
    if header_row is None:
        raise PtoImportError(["no header row found: need columns Name, From, To (and Code) "
                              f"in the first {_HEADER_SCAN_ROWS} rows"])

    def cell(row, key):
        j = columns.get(key)
        return row[j] if j is not None and j < len(row) else None

    entries: list[PtoEntry] = []
    problems: list[str] = []
    for i in range(header_row + 1, len(rows)):
        row, number = rows[i], i + 1
        name, raw_from, raw_to, raw_code = (cell(row, k) for k in ("name", "from", "to", "code"))
        if all(v is None or str(v).strip() == "" for v in (name, raw_from, raw_to, raw_code)):
            continue
        row_problems = []
        name_text = " ".join(str(name).split()) if name is not None else ""
        if not name_text:
            row_problems.append("name is empty")
        start, end = _to_date(raw_from), _to_date(raw_to)
        if start is None:
            row_problems.append(f"From {raw_from!r} is not a date")
        if end is None:
            row_problems.append(f"To {raw_to!r} is not a date")
        if start and end and end < start:
            row_problems.append(f"To ({end:%d-%b-%Y}) is before From ({start:%d-%b-%Y})")
        code = DEFAULT_PTO_CODE
        if raw_code is not None and str(raw_code).strip():
            parsed = try_parse_code(str(raw_code))
            if parsed is None:
                row_problems.append(f"unknown code {str(raw_code).strip()!r}")
            elif parsed.canonical not in ALLOWED_PTO_CODES:
                row_problems.append(f"code {str(raw_code).strip()!r} ({parsed.canonical}) cannot "
                                    f"be imported as PTO (allowed: "
                                    f"{', '.join(sorted(ALLOWED_PTO_CODES))})")
            else:
                code = parsed.canonical
        if row_problems:
            problems.append(f"row {number}: " + "; ".join(row_problems))
        else:
            entries.append(PtoEntry(name_text, start, end, code, number))
    if problems:
        raise PtoImportError(problems)
    return entries


# ---- name matching --------------------------------------------------------------

def _tokens(name: str) -> frozenset[str]:
    return frozenset(name_key(name).replace(".", "").split())


def _edit_distance(a: str, b: str) -> int:
    if a == b:
        return 0
    dp = list(range(len(b) + 1))
    for i in range(1, len(a) + 1):
        prev, dp[0] = dp[0], i
        for j in range(1, len(b) + 1):
            cur = dp[j]
            dp[j] = min(dp[j] + 1, dp[j - 1] + 1, prev + (a[i - 1] != b[j - 1]))
            prev = cur
    return dp[-1]


def _fuzzy_reason(import_tokens: frozenset[str], roster_tokens: frozenset[str]) -> str | None:
    if abs(len(import_tokens) - len(roster_tokens)) == 1 and (
            import_tokens < roster_tokens or roster_tokens < import_tokens):
        return "one name part missing or extra"
    if len(import_tokens) == len(roster_tokens) and len(import_tokens) >= 1:
        only_i, only_r = sorted(import_tokens - roster_tokens), sorted(roster_tokens - import_tokens)
        if len(only_i) == 1 and _edit_distance(only_i[0], only_r[0]) <= 2:
            return f"spelling differs ({only_i[0]!r} vs {only_r[0]!r})"
    a, b = " ".join(sorted(import_tokens)), " ".join(sorted(roster_tokens))
    if a != b and _edit_distance(a, b) <= 2:
        return "spelling differs"
    return None


def match_names(
    import_names: Iterable[str],
    roster_names: Iterable[str],
    confirmed: Mapping[str, str] | None = None,
) -> PtoMatchReport:
    """Match import names to roster names; see the module docstring for the rules."""
    roster = list(dict.fromkeys(roster_names))
    roster_by_key = {name_key(n): n for n in roster}
    confirmed_by_key = {name_key(k): v for k, v in (confirmed or {}).items()}
    report = PtoMatchReport()
    via: set[str] = set()
    for name in dict.fromkeys(import_names):
        itoks = _tokens(name)
        exact = [r for r in roster if _tokens(r) == itoks]
        if len(exact) == 1:
            report.exact[name] = exact[0]
            continue
        target = confirmed_by_key.get(name_key(name))
        if target is not None and name_key(target) in roster_by_key:
            report.exact[name] = roster_by_key[name_key(target)]
            via.add(name)
            continue
        if len(exact) > 1:
            report.needs_confirmation[name] = [Candidate(r, "same name as another person")
                                               for r in exact]
            continue
        candidates = []
        for r in roster:
            reason = _fuzzy_reason(itoks, _tokens(r))
            if reason:
                candidates.append(Candidate(r, reason))
        if candidates:
            report.needs_confirmation[name] = sorted(candidates, key=lambda c: c.roster_name)
        else:
            report.unmatched.append(name)
    report.via_confirmation = frozenset(via)
    return report


