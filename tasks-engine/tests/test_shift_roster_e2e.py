# --- helpers ------------------------------------------------------------------


def task_json(c):
    return next(t for t in c.get("/tasks").json() if t["id"] == TASK_ID)


def wait_for_state(c, state, step=None, timeout=STEP_TIMEOUT):
    """Poll GET /tasks until the task is in `state` (at `step`); fail fast on an error state."""
    deadline = time.monotonic() + timeout
    while True:
        t = task_json(c)
        if t["state"] == state and (step is None or t["currentStep"] == step):
            return t
        if t["state"] == "error":
            pytest.fail(f"the task hit an error while waiting for {state}/{step}: {t['error']}")
        if time.monotonic() > deadline:
            pytest.fail(f"timed out waiting for {state}/{step}; the task is {t['state']}/{t['currentStep']}")
        time.sleep(0.2)


def wait_for_error(c, timeout=STEP_TIMEOUT):
    deadline = time.monotonic() + timeout
    while True:
        t = task_json(c)
        if t["state"] == "error":
            return t
        if time.monotonic() > deadline:
            pytest.fail(f"timed out waiting for an error; the task is {t['state']}/{t['currentStep']}")
        time.sleep(0.2)


def post(c, path, **kw):
    r = c.post(f"/tasks/{TASK_ID}{path}", **kw)
    assert r.status_code == 200, (path, r.status_code, r.text[:200])
    return r.json()


def get(c, path):
    r = c.get(f"/tasks/{TASK_ID}{path}")
    assert r.status_code == 200, (path, r.status_code, r.text[:200])
    return r.json()


def upload(c, input_id, name, data):
    r = c.post(f"/tasks/{TASK_ID}/upload", params={"input": input_id},
               files={"file": (name, data, "application/octet-stream")})
    assert r.status_code == 200, r.text[:200]
    return r.json()


def upload_world_file(c, env, input_id):
    return upload(c, input_id, f"{input_id}.xlsx", env.files[input_id].read_bytes())


def prepare_and_choose_cycle(c, env, cycle=CYCLE):
    for input_id in ("roster", "holidays", "pto"):
        assert upload_world_file(c, env, input_id)["ok"]
    prepared = post(c, "/prepare")
    assert prepared["ok"], prepared
    assert post(c, "/params", json={"params": {"cycle": cycle}})["ok"]


def start(c):
    r = post(c, "/start")
    assert r["ok"], r
    return r


def answer_form(c, env):
    """Save defaults for every required question (what the form's single Save does)."""
    form = get(c, "/form")
    assert form["ok"], form
    answers = kit()["synth"].answer_defaults(form["schema"])
    for fid in list(answers):
        if fid.startswith("pto:"):
            answers[fid] = "Person 07"  # the near name in the synthetic PTO import
    saved = post(c, "/form", json={"answers": answers})
    assert saved == {"ok": True, "pending": []}, saved
    return answers


def edit_draft_in_place(env, edits):
    """The user edits cells in Excel and saves the draft under the same name (the hidden
    snapshot sheet and the sidecar stay)."""
    k = kit()
    roster = k["load_roster"](env.draft, k["SHEET"])
    resolved = {roster.address(roster.find(name)[0], d): text for (name, d), text in edits.items()}
    tmp = env.draft.with_name("excel-save.xlsx")
    k["patch_workbook"](env.draft, tmp, k["SHEET"], resolved)
    for attempt in range(20):  # a scanner/indexer may hold the fresh file for a moment (as on a real desktop)
        try:
            os.replace(tmp, env.draft)  # a save in place replaces the file
            break
        except PermissionError:
            if attempt == 19:
                raise
            time.sleep(0.25)


def all_log_text(c):
    entries = c.get(f"/tasks/{TASK_ID}/log").json()
    assert isinstance(entries, list)
    return entries, "\n".join(e["text"] for e in entries)


def history(c):
    body = get(c, "/history")
    assert body["ok"]
    return body["runs"]


# --- the full lifecycle ---------------------------------------------------------


def test_full_lifecycle(env, client):
    c = client
    k = kit()
    started = time.monotonic()

    # 1. manifest parsed by GET /tasks: what the Tasks app renders
    t = task_json(c)
    assert {"id", "displayName", "state", "error", "currentStep", "steps",
            "notifications", "inputs", "prepare"} <= set(t)
    assert (t["state"], t["prepare"]) == ("resting", True)
    assert [i["id"] for i in t["inputs"]] == ["roster", "rotation_config", "holidays", "pto", "cycle"]
    assert {i["id"]: i["required"] for i in t["inputs"]} == {
        "roster": True, "rotation_config": True, "holidays": False, "pto": False, "cycle": True}
    # the Holiday Roster is optional and kept on file; only the roster gates Check inputs
    holidays_input = next(i for i in t["inputs"] if i["id"] == "holidays")
    assert holidays_input["persist"] is True and "optional" in holidays_input["label"].lower()
    assert [(s["id"], s["type"]) for s in t["steps"]] == [
        ("analyze", "python"), ("answers", "review"), ("build_draft", "python"), ("review_draft", "review"),
        ("diff_draft", "python"), ("confirm_diff", "confirm"), ("finalize", "python")]
    assert all(isinstance(s["label"], str) and s["label"] for s in t["steps"])
    gates = {s["id"]: s["gate"] for s in t["steps"] if s["gate"]}
    assert gates == {
        "answers": {"type": "form", "schema": "output/ask-me.json", "answers": "output/ask-me-answers.json"},
        "review_draft": {"type": "flags", "file": "output/flags.json"},
        "confirm_diff": {"type": "diff", "file": "output/roster-diff.json"},
    }

    # 2. nothing uploaded yet; start is refused with the missing required inputs
    inputs = get(c, "/inputs")
    assert inputs["ok"] and inputs["params"] == {}
    assert {i["id"]: i["present"] for i in inputs["inputs"]} == {
        "roster": False, "rotation_config": True, "holidays": False, "pto": False, "cycle": False}
    refused = post(c, "/start")
    assert refused["ok"] is False and refused["missing"] == ["roster", "cycle"]
    assert task_json(c)["state"] == "resting"

    # 3. uploads, prepare refused until the roster exists (the Holiday Roster is not needed for it)
    early = post(c, "/prepare")
    assert early["ok"] is False and early["missing"] == ["roster"]
    up = upload_world_file(c, env, "roster")
    master_sha = sha(env.files["roster"])
    assert up["ok"] and up["sha256"] == master_sha and up["size"] == env.files["roster"].stat().st_size
    assert sha(env.p("input/roster.xlsx")) == master_sha
    # no upload and no reference file: prepare still runs and says so (every cycle stays disabled)
    bare = post(c, "/prepare")
    assert bare["ok"] and bare["options"]["holiday_source"] is None
    assert not any(x["enabled"] for x in bare["options"]["cycles"])
    assert any("no Holiday Roster: upload one or add one to roster-reference" in x["message"]
               for x in bare["options"]["problems"])
    assert upload_world_file(c, env, "holidays")["ok"]
    prepared = post(c, "/prepare")
    assert prepared["options"]["holiday_source"]["kind"] == "uploaded"
    assert prepared["ok"] and isinstance(prepared["options"], dict)

    # 4. options: a disabled cycle with its reason, a default
    options = get(c, "/options")
    assert options == {"ok": True, "options": prepared["options"]}
    cycles = options["options"]["cycles"]
    assert all({"id", "label", "enabled"} <= set(x) for x in cycles)
    disabled = [x for x in cycles if x["enabled"] is False]
    assert disabled and all(x["reason"] for x in disabled)
    assert options["options"]["default"] == CYCLE
    assert next(x for x in cycles if x["id"] == CYCLE)["enabled"] is True

    # 5. params: a disabled cycle is refused with its own reason, an enabled one is saved
    bad = post(c, "/params", json={"params": {"cycle": disabled[0]["id"]}})
    assert bad == {"ok": False, "reason": disabled[0]["reason"]}
    assert post(c, "/params", json={"params": {"cycle": "1999-01"}})["ok"] is False
    assert post(c, "/params", json={"params": {"roster": "x"}})["ok"] is False  # not a select input
    assert not env.p("input/run-params.json").exists()
    ok = post(c, "/params", json={"params": {"cycle": CYCLE}})
    assert ok == {"ok": True, "params": {"cycle": CYCLE}}
    saved = json.loads(env.p("input/run-params.json").read_text(encoding="utf-8"))
    assert saved["params"] == {"cycle": CYCLE} and saved["saved_at"]
    assert upload_world_file(c, env, "pto")["ok"]  # optional input: does not invalidate the options
    assert get(c, "/options")["options"] is not None
    inputs = get(c, "/inputs")
    assert all(i["present"] for i in inputs["inputs"]) and inputs["params"] == {"cycle": CYCLE}
    by_id = {i["id"]: i for i in inputs["inputs"]}
    assert by_id["roster"]["sha256"] == master_sha and by_id["roster"]["filename"] == "roster.xlsx"

    # 6. start accepted; the answers form gate is reached
    config_before = env.config_before
    start(c)
    assert post(c, "/start")["ok"] is False  # already running
    t = wait_for_state(c, "awaiting_review", "answers")
    assert t["error"] is None
    # inputs are frozen while a run is in progress
    assert post(c, "/prepare")["ok"] is False
    assert upload(c, "roster", "roster.xlsx", b"PK-other")["ok"] is False
    assert post(c, "/params", json={"params": {"cycle": CYCLE}})["ok"] is False
    assert sha(env.p("input/roster.xlsx")) == master_sha

    # 7. the form: pending required fields; approve is refused while some are pending
    form = get(c, "/form")
    assert form["ok"] and form["answers"] == {}
    fields = form["schema"]["fields"]
    assert fields and all(f["type"] == "select" and f["group"] and f["label"] and f["options"] for f in fields)
    required = [f["id"] for f in fields if f.get("required")]
    assert required and form["pending"] == required
    refusal = post(c, "/approve")
    assert refusal["ok"] is False and refusal["pending"] == required
    assert task_json(c)["state"] == "awaiting_review"  # still parked at the gate

    # bad answers are refused without touching the file; partial answers shrink `pending`
    unknown = post(c, "/form", json={"answers": {"../evil": "x"}})
    assert unknown["ok"] is False and unknown["invalid"] == ["../evil"]
    wrong_value = post(c, "/form", json={"answers": {required[0]: "NOT-AN-OPTION"}})
    assert wrong_value["ok"] is False and wrong_value["invalid"] == [required[0]]
    assert post(c, "/form", json={"answers": "not an object"})["ok"] is False
    assert c.post(f"/tasks/{TASK_ID}/form", content=b"nope").json()["ok"] is False
    assert not env.p("output/ask-me-answers.json").exists()
    first = k["synth"].answer_defaults(form["schema"])
    one = post(c, "/form", json={"answers": {required[0]: first[required[0]]}})
    assert one == {"ok": True, "pending": required[1:]}
    assert post(c, "/approve")["ok"] is False  # still pending
    answers = answer_form(c, env)
    assert get(c, "/form")["pending"] == [] and get(c, "/form")["answers"] == answers
    assert json.loads(env.p("output/ask-me-answers.json").read_text(encoding="utf-8")) == answers

    # 8. approve -> build_draft runs -> the flags gate
    assert post(c, "/approve") == {"ok": True}
    t = wait_for_state(c, "awaiting_review", "review_draft")
    assert env.draft.exists()
    flags = get(c, "/flags")
    assert flags["ok"] and set(flags["flags"]) == {"counts", "flags"}
    counts = flags["flags"]["counts"]
    rows = flags["flags"]["flags"]
    assert set(counts) == {"error", "warning", "info"} and sum(counts.values()) == len(rows) > 0
    assert {sev: sum(1 for f in rows if f["severity"] == sev) for sev in counts} == counts
    assert all({"key", "kind", "severity", "message"} <= set(f) for f in rows)
    # flags can have no person / no date (staffing flags): the UI types must tolerate null
    assert any(f["person"] is None for f in rows) and any(f["date"] is None for f in rows)
    # report-data.json points at the draft, and that path reaches the UI through the notification
    report = json.loads(env.p("output/report-data.json").read_text(encoding="utf-8"))
    assert report["stage"] == "draft" and report["workbook_path"] == f"output/{DRAFT_NAME}"
    assert report["summary"]["cycle"] == CYCLE and report["summary"]["flags"] == counts
    draft_notes = [n for n in t["notifications"] if n["kind"] == "task.review_ready" and n["outputPath"]]
    assert len(draft_notes) == 1
    note = draft_notes[0]
    assert Path(note["outputPath"]) == env.draft.resolve() and Path(note["outputPath"]).is_absolute()
    assert note["body"] == next(s for s in json.loads(env.p("task.json").read_text())["steps"]
                                if s["id"] == "review_draft")["reviewMessage"]
    assert get(c, "/diff") == {"ok": True, "diff": None}  # no comparison yet at this gate
    # the Open button: the backend opens exactly that file
    assert post(c, f"/notifications/{note['id']}/open") == {"ok": True}
    assert env.opened == [str(env.draft.resolve())]
    # the form gate's notification carried no file (the draft did not exist yet)
    answers_note = next(n for n in t["notifications"] if n["body"].startswith("A few questions"))
    assert answers_note["outputPath"] is None
    assert sha(env.p("input/roster.xlsx")) == master_sha

    # 9. the user edits the draft in Excel and saves it in place, then approves
    draft_before = sha(env.draft)
    edit_draft_in_place(env, EDITS)
    assert sha(env.draft) != draft_before
    assert post(c, "/approve") == {"ok": True}
    t = wait_for_state(c, "awaiting_send", "confirm_diff")

    # 10. the diff gate: exactly the three edited cells, nothing blocking
    diff = get(c, "/diff")["diff"]
    assert diff["cycle"] == CYCLE and diff["blocking"] == [] and diff["outside_changes"] == []
    assert {(x["person"], x["date"]): x["after"] for x in diff["changes"]} == {
        (n, d.isoformat()): text for (n, d), text in EDITS.items()}
    assert all(set(x) >= {"person", "date", "before", "after"} for x in diff["changes"])
    assert set(diff["flags"]) >= {"new", "resolved", "remaining"} and isinstance(diff["flags"]["remaining"], int)
    assert diff["saved_draft"] == DRAFT_NAME
    confirm_notes = [n for n in t["notifications"] if n["body"].startswith("Look at every changed cell")]
    assert len(confirm_notes) == 1 and Path(confirm_notes[0]["outputPath"]) == env.draft.resolve()
    # actions that do not belong to this gate are refused
    assert post(c, "/approve")["ok"] is False
    assert post(c, "/reject")["ok"] is False

    # a diff with blocking issues cannot be sent (the diff file is restored byte for byte after)
    diff_path = env.p("output/roster-diff.json")
    original_diff = diff_path.read_bytes()
    blocked = {**diff, "blocking": [{"kind": "SNAPSHOT_TAMPERED", "message": "synthetic blocker"}]}
    diff_path.write_text(json.dumps(blocked), encoding="utf-8")
    refused = post(c, "/send")
    assert refused["ok"] is False and refused["blocking"] == blocked["blocking"] and refused["reason"]
    assert task_json(c)["state"] == "awaiting_send"
    diff_path.write_bytes(original_diff)
    assert not env.p("output/final").exists() and not env.p("output/backups").exists()

    # 11. send -> finalize -> back to resting
    master_copy = env.tmp / "master-copy.xlsx"  # the task's cleanup removes input/roster.xlsx after the run
    shutil.copy2(env.p("input/roster.xlsx"), master_copy)
    assert sha(master_copy) == master_sha
    assert post(c, "/send") == {"ok": True}
    t = wait_for_state(c, "resting")
    assert t["error"] is None and t["currentStep"] is None

    # 12. what the run left behind
    final = env.p(f"output/final/{FINAL_NAME}")
    assert final.exists()
    # input cleanup (manifest `cleanup.onComplete`): the weekly uploads are gone, the persisted
    # Holiday Roster stays on file, nothing else under input/ is left but dotfiles
    assert not env.p("input/roster.xlsx").exists() and not env.p("input/pto-import.xlsx").exists()
    assert env.p("input/holiday-roster.xlsx").exists()
    assert not env.p("input/run-params.json").exists() and not env.p("output/options.json").exists()
    assert sorted(p.name for p in env.p("input").iterdir() if not p.name.startswith(".")) == ["holiday-roster.xlsx"]
    # package level: only the roster sheet part differs from the master
    k["pkgdiff"].assert_only_changed(master_copy, final, {SHEET_PART})
    # cell level: exactly the cells where the (edited) draft differs from the master
    master_grid = k["grid"](master_copy)
    draft_grid = k["grid"](env.draft)
    final_grid = k["grid"](final)
    expected = {key for key in master_grid if draft_grid[key] != master_grid[key]}
    differs = {key for key in final_grid if final_grid[key] != master_grid[key]}
    assert len(expected) > 300 and differs == expected
    assert all(final_grid[key] == draft_grid[key] for key in expected)
    for key, text in EDITS.items():
        assert final_grid[key] == text
    assert all(date(2026, 11, 29) <= d <= date(2027, 1, 1) for _, d in differs)
    # next-year file, backup, audit
    assert env.p("output/final/roster - 2027.xlsx").exists()
    backups = list(env.p("output/backups").glob("*.xlsx"))
    assert len(backups) == 1 and sha(backups[0]) == master_sha
    assert list(env.p("output/audit").glob("*.json")) and list(env.p("output").rglob("audit.log.jsonl"))
    audit_text = "\n".join(p.read_text(encoding="utf-8") for p in env.p("output/audit").glob("*.json"))
    assert master_sha in audit_text
    # config: updated, the previous file kept verbatim in config/backups
    config_backups = list(env.p("config/backups").glob("rotation-config.*.json"))
    assert len(config_backups) == 1 and config_backups[0].read_bytes() == config_before
    assert env.p("config/rotation-config.json").read_bytes() != config_before
    # report-data now points at the FINAL workbook
    report = json.loads(env.p("output/report-data.json").read_text(encoding="utf-8"))
    assert report["stage"] == "final" and report["workbook_path"] == f"output/final/{FINAL_NAME}"
    assert report["summary"]["cycle"] == CYCLE and report["summary"]["master_sha256"] == master_sha
    assert report["summary"]["user_changes"] == len(EDITS)
    # the completed notification carries the final workbook for the Open button
    done_note = next(n for n in t["notifications"] if n["kind"] == "task.completed")
    assert Path(done_note["outputPath"]) == final.resolve()
