def test_inputs_negative_and_traversal(env, client):
    c = client
    good = env.files["roster"].read_bytes()

    def no_file_outside_inputs():
        """Uploads only ever create files under <task>/input (nothing in tmp root, output, scripts, ...)."""
        allowed_roots = {env.p("input").resolve(), (env.tmp / "world").resolve(), env.p("scripts").resolve(),
                         (env.apps / "shared").resolve(), env.p("config").resolve()}
        stray = [p for p in env.tmp.rglob("*")
                 if p.is_file() and not any(p.resolve().is_relative_to(r) for r in allowed_roots)
                 and p.name not in ("task.json", "history.jsonl")]
        assert stray == [], stray

    # bad extensions (also case and double-extension tricks) are refused
    for name in ("roster.xls", "roster.exe", "roster.xlsx.exe", "evil.py", "evil.ps1", "noext", "roster.XLSM"):
        r = upload(c, "roster", name, good)
        assert r["ok"] is False and r["reason"], name
    # a part without a filename is not an upload at all (FastAPI itself answers 422)
    nameless = c.post(f"/tasks/{TASK_ID}/upload", params={"input": "roster"}, files={"file": ("", good, "x")})
    assert nameless.status_code == 422 or nameless.json()["ok"] is False
    assert upload(c, "roster", "x.xlsx", b"")["ok"] is False  # empty file
    # unknown / wrong-kind / traversal-looking input ids
    for input_id in ("nope", "../roster", "..\\..\\roster", "input/roster", "cycle", ""):
        r = c.post(f"/tasks/{TASK_ID}/upload", params={"input": input_id},
                   files={"file": ("a.xlsx", good, "application/octet-stream")}).json()
        assert r["ok"] is False, input_id
    assert c.post(f"/tasks/{TASK_ID}/upload", files={"file": ("a.xlsx", good, "x")}).json()["ok"] is False
    assert c.post(f"/tasks/{TASK_ID}/upload", params={"input": "roster"}).json()["ok"] is False  # no file part
    assert get(c, "/inputs")["inputs"][0]["present"] is False
    assert not env.p("input/roster.xlsx").exists()

    # a client filename with path segments is reduced to its basename; the bytes still land
    # only at the manifest's dest
    r = upload(c, "roster", "..\\..\\..\\evil\\roster.xlsx", good)
    assert r["ok"] and r["filename"] == "roster.xlsx" and sha(env.p("input/roster.xlsx")) == sha(env.files["roster"])
    r = upload(c, "holidays", "../../x/holiday.XLSX", env.files["holidays"].read_bytes())  # case-insensitive ext
    assert r["ok"] and r["filename"] == "holiday.XLSX"
    no_file_outside_inputs()
    assert sorted(p.name for p in env.p("input").iterdir() if not p.name.startswith(".")) == [
        "holiday-roster.xlsx", "roster.xlsx"]
    assert not list(env.p("input").glob("*.upload")) and not list(env.p("input").glob("*.tmp"))
    # the task id itself cannot traverse
    for bad_id in ("..", "..%2fshift-roster", "%2e%2e"):
        r = c.get(f"/tasks/{bad_id}/inputs")
        assert r.status_code == 404 or r.json().get("ok") is False, bad_id

    # prepare, then re-uploading an input the prepare step reads invalidates the options and
    # the cycle choice made from them
    assert post(c, "/prepare")["ok"]
    assert post(c, "/params", json={"params": {"cycle": CYCLE}})["ok"]
    assert get(c, "/options")["options"] is not None
    assert upload(c, "roster", "roster.xlsx", good)["ok"]
    assert get(c, "/options")["options"] is None
    assert get(c, "/inputs")["params"] == {}
    assert post(c, "/start")["missing"] == ["cycle"]  # roster + holidays present, cycle must be redone

    # params / form with path-like or bogus keys never write anywhere
    assert post(c, "/params", json={"params": {"../x": "v"}})["ok"] is False
    assert post(c, "/params", json={"params": {"cycle": "2026-12"}})["ok"] is False  # no options yet
    assert post(c, "/params", json={})["ok"] is False
    assert c.post(f"/tasks/{TASK_ID}/params", content=b"[1]").json()["ok"] is False
    assert post(c, "/form", json={"answers": {"a": "b"}})["ok"] is False  # not at the form gate
    assert get(c, "/diff") == {"ok": True, "diff": None}
    assert get(c, "/flags") == {"ok": True, "flags": None}
    # approving or sending a resting task does nothing
    assert post(c, "/approve")["ok"] is False and post(c, "/send")["ok"] is False
    # an unreadable options file gives a readable refusal, never a 500
    env.p("output").mkdir(exist_ok=True)
    env.p("output/options.json").write_text("{not json", encoding="utf-8")
    assert get(c, "/options")["ok"] is False
    env.p("output/options.json").unlink()
    assert task_json(c)["state"] == "resting"
    no_file_outside_inputs()


def test_output_folder_junction_is_refused(env, client, tmp_path):
    """A symlink/junction planted at output/ must never be followed."""
    c = client
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "options.json").write_text(json.dumps({"cycles": []}), encoding="utf-8")
    link = env.p("output")
    try:
        os.symlink(outside, link, target_is_directory=True)
    except (OSError, NotImplementedError):
        done = subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(outside)], capture_output=True) \
            if sys.platform == "win32" else None
        if done is None or done.returncode != 0:
            pytest.skip("cannot create a symlink or junction here")
    reply = get(c, "/options")
    assert reply["ok"] is False and "symbolic" in reply["reason"]
    assert get(c, "/flags")["ok"] is False and get(c, "/diff")["ok"] is False
