_KIT = {}


def kit():
    """The task's own synthetic-data helpers (imported lazily from the PMO Desk repo)."""
    if not _KIT:
        for p in (SHARED_SRC / "roster_lib" / "tests", SHARED_SRC, TASK_SRC / "tests", TASK_SRC / "scripts"):
            if str(p) not in sys.path:
                sys.path.append(str(p))
        import synth
        from draft_testkit import SHEET, grid
        from roster_lib import pkgdiff
        from roster_lib.roster_io import load_roster
        from roster_lib.xlsx_patch import patch_workbook

        _KIT.update(synth=synth, SHEET=SHEET, grid=grid, pkgdiff=pkgdiff,
                    load_roster=load_roster, patch_workbook=patch_workbook)
    return _KIT


def sha(path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


class Env:
    """A temp tasks root holding a copy of the shift-roster task + synthetic input files."""

    def __init__(self, tmp_path: Path):
        k = kit()
        self.tmp = tmp_path
        self.apps = tmp_path / "apps"
        self.task = self.apps / TASK_ID
        # the task copy: manifest + scripts only; the scripts import ../shared/roster_lib
        shutil.copytree(TASK_SRC / "scripts", self.task / "scripts", ignore=shutil.ignore_patterns("__pycache__"))
        shutil.copy2(TASK_SRC / "task.json", self.task / "task.json")
        shutil.copytree(SHARED_SRC / "roster_lib", self.apps / "shared" / "roster_lib",
                        ignore=shutil.ignore_patterns("__pycache__", "tests", "examples"))
        # synthetic inputs, generated by the task's own test helpers in a separate folder
        self.world = k["synth"].build_world(tmp_path / "world")
        self.files = {"roster": self.world.paths.roster, "holidays": self.world.paths.holidays,
                      "pto": self.world.paths.pto}
        (self.task / "config").mkdir()
        shutil.copy2(self.world.paths.config, self.task / "config" / "rotation-config.json")
        self.config_before = (self.task / "config" / "rotation-config.json").read_bytes()
        self.opened: list[str] = []
        # where the task looks for a Holiday Roster when none is uploaded: <apps>/shared/roster-reference
        self.reference_dir = self.apps / "shared" / "roster-reference"

    def add_reference(self, name: str = "Holiday Roster 2026.xlsx") -> Path:
        """A synthetic reference Holiday Roster (never a real file)."""
        self.reference_dir.mkdir(parents=True, exist_ok=True)
        path = self.reference_dir / name
        kit()["synth"].write_matrix(path)
        return path

    # task-folder paths
    def p(self, rel: str) -> Path:
        return self.task / rel

    @property
    def draft(self) -> Path:
        return self.p(f"output/{DRAFT_NAME}")


